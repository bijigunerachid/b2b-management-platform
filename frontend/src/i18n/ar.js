function plural(count, forms) {
  const n = Number(String(count).replace(/\D/g, ""));
  if (n === 1) return forms.one;
  if (n === 2) return forms.two;
  const rest = n % 100;
  if (rest >= 3 && rest <= 10) return forms.few;
  return forms.many;
}

